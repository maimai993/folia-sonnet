import type { Line, LyricData, Word } from '../../types';
import type { PlayUrlSubtitle } from './api';

// src/services/bilibili/bilibiliLyrics.ts
// 视频有字幕的话，就把字幕当歌词用。
//
// B 站的字幕不是一个文件包两种语言，而是**一种语言一条轨**（`subtitle.subtitles[]`，
// 每项带 lan / lan_doc / subtitle_url）。所以「中英双语」不是一条轨里带翻译，
// 而是两条轨：一条中文、一条英文。这里负责把它们合并成一行行带 translation 的歌词。

/** 字幕文件里的一条：从 `from` 到 `to`（秒）说了 `content`。 */
interface SubtitleCue {
    from?: number;
    to?: number;
    content?: string;
}

interface SubtitleBody {
    body?: SubtitleCue[];
}

/**
 * 语言代码归成一个大类。
 *
 * B 站自己的代码很乱：`zh-CN` / `zh-Hans` / `ai-zh` 都是中文，`en` / `en-US` /
 * `ai-en` 都是英文。
 */
const languageOf = (lan: string): 'zh' | 'en' | 'other' => {
    const lower = lan.toLowerCase();
    if (lower.includes('zh') || lower === 'ai-zh') return 'zh';
    if (lower.includes('en')) return 'en';
    return 'other';
};

/** 自动生成的字幕比 UP 主上传的差一档，同一个语言优先用上传的那条。 */
const isAutoGenerated = (lan: string): boolean => lan.toLowerCase().startsWith('ai-');

/**
 * 从字幕列表里挑出要用的几条。
 *
 * 中文和英文各挑一条（同一个语言优先 UP 主上传的，没有才用自动生成的）；
 * 只有别的语言时才退而求其次拿第一条。一条都没有就是这条视频没有字幕。
 */
export const pickSubtitleTracks = (tracks: PlayUrlSubtitle[]): {
    primary: PlayUrlSubtitle | null;
    secondary: PlayUrlSubtitle | null;
} => {
    const usable = tracks.filter(track => Boolean(track.subtitle_url));
    const pickOf = (kind: 'zh' | 'en'): PlayUrlSubtitle | null => {
        const same = usable.filter(track => languageOf(track.lan ?? '') === kind);
        return same.find(track => !isAutoGenerated(track.lan ?? '')) ?? same[0] ?? null;
    };
    const zh = pickOf('zh');
    const en = pickOf('en');
    if (zh || en) return { primary: zh ?? en, secondary: zh ? en : null };
    return { primary: usable[0] ?? null, secondary: null };
};

/** 抓一条字幕轨的内容。协议相对的地址要补 https:，不然 WebView 会拦。 */
export const fetchSubtitleCues = async (
    subtitleUrl: string,
    fetchJson: <T>(url: string) => Promise<T>,
): Promise<SubtitleCue[]> => {
    const absolute = subtitleUrl.startsWith('//') ? `https:${subtitleUrl}` : subtitleUrl;
    const body = await fetchJson<SubtitleBody>(absolute);
    return Array.isArray(body?.body) ? body.body : [];
};

/**
 * 把主轨和（可选的）副轨合成歌词。
 *
 * 合并规则：以主轨的每一句为准，副轨里**时间重叠最多**的那一句当它的翻译。
 * 不能按下标一一对应 —— 两种语言断句不一样，一条英文可能横跨两句中文。
 */
export const buildLyricsFromCues = (
    primary: SubtitleCue[],
    secondary: SubtitleCue[] = [],
    meta: { title?: string; artist?: string } = {},
): LyricData => {
    const primaryLines = cuesToLines(primary);
    if (!secondary.length) return withMeta(primaryLines, meta);

    const secondaryLines = cuesToLines(secondary);
    const merged = primaryLines.map(line => {
        const match = bestOverlap(line, secondaryLines);
        return match ? { ...line, translation: match.fullText } : line;
    });
    return withMeta(merged, meta);
};

/**
 * 一句字幕 → 一行歌词。
 *
 * 时间上这个仓库有两套单位：`Line` 用毫秒，`Word` 用**秒**。字幕接口本来给的就是秒，
 * 所以词的时间原样用，行的时间乘 1000。
 */
const cuesToLines = (cues: SubtitleCue[]): Line[] => {
    const lines: Line[] = [];
    for (const cue of cues) {
        const text = (cue.content ?? '').trim();
        if (!text) continue;
        const from = Math.max(0, cue.from ?? 0);
        // 没有 to 的（少见）给 3 秒，免得零长度的一行在时间轴上永远不出现。
        const to = Math.max(from + 0.5, cue.to ?? from + 3);
        const word: Word = { text, startTime: from, endTime: to };
        lines.push({
            words: [word],
            startTime: Math.round(from * 1000),
            endTime: Math.round(to * 1000),
            fullText: text,
        });
    }
    // 字幕文件偶尔不是按时间排的，排一遍才对得上播放进度。
    lines.sort((a, b) => a.startTime - b.startTime);
    return lines;
};

/** 找和这一行重叠最多的那一行。一点不重叠就不给翻译，别硬塞一句不相干的。 */
const bestOverlap = (line: Line, candidates: Line[]): Line | null => {
    let best: Line | null = null;
    let bestMs = 0;
    for (const candidate of candidates) {
        const overlap = Math.min(line.endTime, candidate.endTime) - Math.max(line.startTime, candidate.startTime);
        if (overlap > bestMs) {
            bestMs = overlap;
            best = candidate;
        }
    }
    return best;
};

const withMeta = (lines: Line[], meta: { title?: string; artist?: string }): LyricData => ({
    lines,
    ...(meta.title ? { title: meta.title } : {}),
    ...(meta.artist ? { artist: meta.artist } : {}),
});
