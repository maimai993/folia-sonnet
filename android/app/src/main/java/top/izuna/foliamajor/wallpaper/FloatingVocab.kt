        private fun isSpace(c: Char): Boolean {
            return Character.isWhitespace(c)
        }

        private fun isAscii(c: Char): Boolean {
            return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9')
        }

        private fun isCjk(c: Char): Boolean {
            return (c >= '\u4e00' && c <= '\u9fff')
                    || (c >= '\u3040' && c <= '\u30ff')
                    || (c >= '\uac00' && c <= '\ud7af')
        }

        private fun isAsciiInner(c: Char): Boolean {
            return isAscii(c) || c == '\'' || c == '-' || c == '\u2019'
        }

        /**
         * 整行文本 → 词区间。
         *
         * 两条路一起用，因为**哪一条单着都不够**：
         * - ICU（系统自带的分词器）认识「想想 / 天真 / 无邪」这类常用词，但它切不到歌词里的
         *   偏词，而且某些 ROM 上它被裁成了逐字；
         * - 随包那本词典是**分词器自己的 token 表**，覆盖的是另一批词，覆盖率靠它兜底。
         *
         * 所以：先跑 ICU，再把 ICU 切剩下的连续单字交给词典做最长匹配合并（{@link #mergeCjk}）。
         * 返回的区间一定是 [0, text.length) 的连续划分，下游可以直接拿去 `measureText`。
         */
        @JvmStatic
        fun split(text: String?): List<Segment> {
            if (text == null || text.isEmpty()) return ArrayList()
            val icu = splitWithIcu(text)
            if (icu != null && !icu.isEmpty()) return mergeCjk(text, icu)
            return splitWithDict(text)
        }

        /**
         * 系统 ICU 的分词结果。
         *
         * 拿不到（ROM 裁了 ICU 数据 / 版本太老）就返回 null，让调用方退到词典 —— 不要抛出去：
         * 这层每帧都在画，抛一次就是整个悬浮窗黑掉。
         */
        private fun splitWithIcu(text: String): List<Segment>? {
            return try {
                val iterator = BreakIterator.getWordInstance(Locale.CHINA)
                iterator.setText(text)
                val out = ArrayList<Segment>()
                var start = iterator.first()
                var end = iterator.next()
                while (end != BreakIterator.DONE) {
                    if (end > start) {
                        out.add(Segment(start, end))
                    }
                    start = end
                    end = iterator.next()
                }
                out
            } catch (ignored: Throwable) {
                null
            }
        }

        /**
         * ICU 没切开的地方（连续的单字）再拿词典最长匹配合成一遍。
         *
         * 只动**连续的 CJK 单字**那一段：ICU 已经切出来的词（哪怕词典里没有）一律保留 ——
         * 它知道的比这本 673 条的词典多。
         */
        private fun mergeCjk(text: String, segments: List<Segment>): List<Segment> {
            val out = ArrayList<Segment>()
            val count = segments.size
            var index = 0
            while (index < count) {
                val segment = segments[index]
                if (segment.end - segment.start != 1 || !isCjk(text[segment.start])) {
                    out.add(segment)
                    index += 1
                    continue
                }
                var groupEnd = segment.end
                var cursor = index + 1
                while (cursor < count) {
                    val next = segments[cursor]
                    if (next.end - next.start != 1 || !isCjk(text[next.start])) break
                    groupEnd = next.end
                    cursor += 1
                }
                out.addAll(splitWithDict(text, segment.start, groupEnd))
                index = cursor
            }
            return out
        }

        /**
         * 这个词在词表里的 id（0–29999）。
         *
         * 悬浮窗上每个词底下那串数字就是它；和播放器里那套用的是同一张表、同一个兜底算法，
         * 所以两边对同一个词印的是同一个数。
         */
        @JvmStatic
        fun idFor(text: String?): Int {
            if (text == null) return 5
            val word = text.trim()
            if (word.isEmpty()) return 5
            val hit = IDS[word]
            if (hit != null) return hit
            // FNV-1a（0x811c9dc5 是 2166136261 的补码写法，直接写十进制字面量会溢出 int）。
            var hash = 0x811c9dc5
            for (index in word.indices) {
                // Char.code 在 Kotlin 2.x 标 Int，xor Long 需要显式转。
                hash = hash xor word[index].code.toLong()
                hash *= 16777619
            }
            val unsigned = hash.toLong() and 0xFFFFFFFFL
            return 5 + (unsigned % 29995).toInt()
        }

        /** 词典最长匹配：西文连成词、空白成段、中日韩按词典切（匹配不上就单字）。 */
        private fun splitWithDict(text: String): List<Segment> {
            return splitWithDict(text, 0, text.length)
        }

        private fun splitWithDict(text: String, from: Int, to: Int): List<Segment> {
            val out = ArrayList<Segment>()
            if (from >= to) return out
            var index = from
            val length = Math.min(to, text.length)
            while (index < length) {
                val head = text[index]
                if (isSpace(head)) {
                    var end = index
                    while (end < length && isSpace(text[end])) end++
                    out.add(Segment(index, end))
                    index = end
                    continue
                }
                if (isAscii(head)) {
                    var end = index
                    while (end < length && isAsciiInner(text[end])) end++
                    out.add(Segment(index, end))
                    index = end
                    continue
                }
                if (isCjk(head)) {
                    var size = Math.min(MAX_WORD, length - index)
                    while (size > 1) {
                        if (WORDS.contains(text.substring(index, index + size))) break
                        size--
                    }
                    out.add(Segment(index, index + size))
                    index += size
                    continue
                }
                out.add(Segment(index, index + 1))
                index++
            }
            return out
        }
    }
